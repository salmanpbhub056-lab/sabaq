-- It is safe to run more than once: it first removes any earlier Sabaq tables and recreates them
-- (this deletes Sabaq data already in the database, so use it on a new/empty project).

drop table if exists group_members cascade;
drop table if exists groups cascade;
drop table if exists settings cascade;
drop table if exists audit cascade;
drop table if exists notifications cascade;
drop table if exists reports cascade;
drop table if exists reviews cascade;
drop table if exists requests cascade;
drop table if exists docs cascade;
drop table if exists listings cascade;
drop table if exists users cascade;

create extension if not exists pgcrypto;

create table users (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null unique,
  pw text not null,
  role text not null default 'student',
  banned boolean not null default false,
  created_at timestamptz not null default now()
);

create table listings (
  id bigint generated by default as identity primary key,
  owner uuid references users(id) on delete cascade,
  type text not null default 't',
  name text not null,
  area text not null,
  levels text[] not null default '{}',
  subjects text[] not null default '{}',
  fee int not null,
  modes text[] not null default '{}',
  gender text not null default 'B',
  exp int not null default 0,
  rating_seed numeric not null default 4,
  bio text not null default '',
  info text not null default '',
  phone text not null,
  photo text,
  status text not null default 'pending',
  note text not null default '',
  vstatus text not null default 'none',
  featured boolean not null default false,
  views int not null default 0,
  created_at timestamptz not null default now()
);

create table docs (
  id uuid primary key default gen_random_uuid(),
  listing bigint not null references listings(id) on delete cascade,
  kind text not null,
  filename text not null,
  mime text not null,
  size int not null default 0,
  data text not null,
  created_at timestamptz not null default now()
);

create table requests (
  id uuid primary key default gen_random_uuid(),
  listing bigint not null references listings(id) on delete cascade,
  student uuid not null references users(id) on delete cascade,
  name text not null,
  phone text not null,
  time_pref text not null default '',
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create table reviews (
  id uuid primary key default gen_random_uuid(),
  listing bigint not null references listings(id) on delete cascade,
  author uuid references users(id) on delete cascade,
  author_name text not null,
  stars int not null check (stars between 1 and 5),
  text text not null,
  reply text not null default '',
  edited boolean not null default false,
  created_at timestamptz not null default now()
);

create table reports (
  id uuid primary key default gen_random_uuid(),
  listing bigint not null references listings(id) on delete cascade,
  reporter uuid references users(id) on delete set null,
  reason text not null,
  details text not null,
  status text not null default 'open',
  created_at timestamptz not null default now()
);

create table notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users(id) on delete cascade,
  text text not null,
  link text not null default '#/me',
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table audit (
  id bigint generated by default as identity primary key,
  text text not null,
  created_at timestamptz not null default now()
);

create table groups (
  id bigint generated by default as identity primary key,
  name text not null,
  exam text not null,
  area text not null,
  base_members int not null default 0,
  created_at timestamptz not null default now()
);

create table group_members (
  group_id bigint not null references groups(id) on delete cascade,
  user_id uuid not null references users(id) on delete cascade,
  primary key (group_id, user_id)
);

create table settings (
  key text primary key,
  value text not null default ''
);

create index on listings (owner);
create index on docs (listing);
create index on requests (listing);
create index on requests (student);
create index on reviews (listing);
create index on notifications (user_id);

-- Security: lock every table so only the server (service key) can read or write.
